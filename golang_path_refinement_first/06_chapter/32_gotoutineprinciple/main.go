// 2、G是被抢占调度
// M是如何让G停下来并调度下一个可运行的G的呢? 答案是：G是被抢占调度的
// 一旦G的抢占标志位被设为
// true，那么在这个G下一次调用函数或方法时，运行时便可以将G抢占并
// 移出运行状态，放入P的本地运行队列中（如果P的本地运行队列已满，
// 那么将放在全局运行队列中），等待下一次被调度

// 3. channel阻塞或网络I/O情况下的调度
// 如果G被阻塞在某个channel操作或网络I/O操作上，那么G会被放置
// 到某个等待队列中，而M会尝试运行P的下一个可运行的G。如果此时P
// 没有可运行的G供M运行，那么M将解绑P，并进入挂起状态。当I/O操
// 作完成或channel操作完成，在等待队列中的G会被唤醒，标记为
// runnable（可运行），并被放入某个P的队列中，绑定一个M后继续执
// 行。

// 4. 系统调用阻塞情况下的调度
// 如果G被阻塞在某个系统调用上，那么不仅G会阻塞，执行该G的M
// 也会解绑P（实质是被sysmon抢走了），与G一起进入阻塞状态。如果
// 此时有空闲的M，则P会与其绑定并继续执行其他G；如果没有空闲的
// M，但仍然有其他G要执行，那么就会创建一个新M（线程）。当系统
// 调用返回后，阻塞在该系统调用上的G会尝试获取一个可用的P，如果有
// 可用P，之前运行该G的M将绑定P继续运行G；如果没有可用的P，那么
// G与M之间的关联将解除，同时G会被标记为runnable，放入全局的运行
// 队列中，等待调度器的再次调度

