package main

// goroutine是由Go运行时管理的用户层轻量级线程
// goroutine的调度模型及演进过程
// 1、G-M模型：限制了Go并发程序的伸缩性，主要是以下几个方面
// 1-1、单一全局互斥锁和集中状态存储的存在导致所有goroutine相关操作（如创建、重新调度等）都要上锁
// 1-2、gotoutine传递问题，经常在M之间传递“可运行的”goroutine会导致调度延迟增大，带来额外的性能损耗
// 1-3、每个M都做内存缓存，导致内存占用过高，数据局部性较差
// 1-4、因系统调用（syscall）而形成的频繁的工作线程阻塞和接触阻塞会带来额外的性能损耗

// 2、G-P-M模型 work stealing算法
// P是一个“逻辑处理器”，每个G要想真正运行起来，首先需要被分配
// 一个P，即进入P的本地运行队列（local runq）中，这里暂忽略全局运
// 行队列（global runq）那个环节。对于G来说，P就是运行它的“CPU”，
// 可以说在G的眼里只有P。但从goroutine调度器的视角来看，真正
// 的“CPU”是M，只有将P和M绑定才能让P的本地运行队列中的G真正运行
// 起来。这样的P与M的关系就好比Linux操作系统调度层面用户线程
// （user thread）与内核线程（kernel thread）的对应关系：多对多
// （N:M）

// 3、抢占式调度
// 解决一旦某个G中出现死循环的代码逻辑，那么G将永久占用分配给它的P和M，而位于同一个P中的其他G将得不到调度，出现饿死的情况，更严重只有一个P时，去他程序G都会饿死的问题
// 抢占式调度原理是在每个函数或方法的入口加上一段额外的代码，让运行时有机会检查是否需要执行抢占调度。这种协作式抢占调度的解决方案只是局部解决了饿死问题，对于没有函数调用而是纯算法循环计算的G，goroutine调度器依然无法抢占

// 4、NUMA调度模型 - 至今没有被列入开发计划

// 对goroutine调度器原理的进一步理解
// 1、G/P/M
// G：代表goroutine，存储了goroutine的执行栈信息、goroutine状态及goroutine的任务函数等。另外G对象是可以重用的
// P：代表逻辑processor，P的数量决定了系统内最大可并行G的数量，P中最有用的是其拥有的各种G对象队列、链表、一些缓存和状态
// M：M代表着真正的执行计算资源。在绑定有效的P后，进入一个调度循环；而调度循环的机制大致是从各种队列、P的本地运行队列中获取G，切换到G的执行栈上并执行G的函数，调用goexit做清理工作并回到M。如此反复。M不保留G状态，这是G可以跨M调度的基础

